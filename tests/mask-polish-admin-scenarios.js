const polishPause=ms=>new Promise(resolve=>setTimeout(resolve,ms));
const polishWait=async predicate=>{for(let i=0;i<400;i++){if(predicate())return;await polishPause(20)}throw Error('Polish/admin scenario timed out')};
const polishAssert=(value,message)=>{if(!value)throw Error(message)};
window.runMaskPolishChecks=async function(){
  const core=window.MosaicCore,$=id=>document.getElementById(id),state=core.state,checks=[],events=[];
  await window.MosaicAccount.ready();$('apiKeyDialog').close();
  const nativeTrack=window.MosaicAccount.track;window.MosaicAccount.track=async type=>events.push(type);
  try{
    const frame=core.makeCanvas(800,600);frame.getContext('2d').fillStyle='#0000ff';frame.getContext('2d').fillRect(0,0,800,600);core.setMaster(frame,'Feather check');
    const mask=core.makeCanvas(800,600);mask.getContext('2d').fillStyle='#fff';mask.getContext('2d').fillRect(100,100,400,300);
    const red=core.makeCanvas(800,600);red.getContext('2d').fillStyle='#ff0000';red.getContext('2d').fillRect(0,0,800,600);
    const sourceId=core.uid('fixture_source'),patch={id:core.uid('fixture_patch'),sourceId,mask,bbox:{x:100,y:100,w:400,h:300},name:'Red patch'};
    state.sources.set(sourceId,{id:sourceId,canvas:red});state.patches.set(patch.id,patch);
    const group=core.assignGroup(patch);group.active=patch.id;core.render();
    const image=core.composeApprovedCanvas().getContext('2d').getImageData(0,0,800,600).data;
    const pixel=(x,y)=>Array.from(image.slice((y*800+x)*4,(y*800+x)*4+4));
    polishAssert(pixel(99,200)[2]===255,'Feather escaped the mask');
    polishAssert(pixel(100,200)[0]<60&&pixel(102,200)[0]>pixel(100,200)[0],'Patch has a hard edge instead of an alpha gradient');
    polishAssert(pixel(120,200)[0]===255,'Feather blurred the interior');
    polishAssert(core.displayedPatchMask(patch).getContext('2d').getImageData(100,200,1,1).data[3]===255,'Feather changed editable mask geometry');
    core.selectGroupMask(group,{showOutline:true});
    const paths=$('selectionOutlineVectors').querySelectorAll('path');
    polishAssert(paths.length>=2&&[...paths].every(p=>getComputedStyle(p).opacity==='1'),'Selection outline is translucent');
    polishAssert(paths[0].getAttribute('stroke')==='#000'&&paths[1].getAttribute('stroke')==='#fff','Outline must alternate black and white');
    checks.push('Feather fades patch alpha inward, preserves sharp texture and editable mask; outline is fully opaque black/white');
    core.resetSelection();core.selectTool('lasso');
    state.lasso=[{x:100,y:100},...Array.from({length:29},(_,i)=>({x:110+i*10,y:100+(i%2?1:-1)})),{x:400,y:100},{x:400,y:400},{x:100,y:400}];
    core.updateMaskWithLasso();core.hideQuickPrompt();
    const before=state.selectionMask.toDataURL(),points=state.selectionPoints.length;
    $('simplifySelectionBtn').click();polishAssert(state.selectionPoints.length<points/2,'Simplify did not straighten the noisy selection');
    $('undoBtn').click();polishAssert(state.selectionMask.toDataURL()===before,'Undo did not restore the previous mask');
    checks.push('Simplify removes zig-zags and supports exact Undo');
    core.selectTool('wand');await polishPause(450);window.MosaicSlimWand.hoverAt({x:300,y:250});
    await polishWait(()=>document.querySelector('.slimsam-hover-overlay').getContext('2d').getImageData(300,250,1,1).data[3]>0);
    const preview=$('slimsamHoverOverlay'),previewContext=preview.getContext('2d');
    polishAssert(previewContext.getImageData(200,200,1,1).data[3]===previewContext.getImageData(300,250,1,1).data[3],'Wand preview still has a distinct border');
    polishAssert(!events.includes('wand_used'),'Hover must not count as a Wand use');
    window.MosaicSlimWand.selectAt({x:300,y:250});polishAssert(events.filter(type=>type==='wand_used').length===1,'Wand selection must count once');
    const glow=document.querySelector('.mask-processing-shimmer'),style=getComputedStyle(glow);
    polishAssert(parseFloat(style.animationDuration)<1&&Number(style.opacity)>.5,'Loading shimmer is too slow or faint');
    checks.push('Wand hover is overlay-only, selection counts once, loading shimmer is faster and more opaque');
    return {passed:checks.length,checks};
  }finally{window.MosaicAccount.track=nativeTrack}
};
window.runAdminGraphChecks=async function(){
  const $=id=>document.getElementById(id),checks=[];await window.MosaicAccount.ready();
  await polishWait(()=>document.querySelectorAll('.admin-chart-plot svg').length===1);
  polishAssert(!$('adminError').textContent,'Admin API returned an error');
  polishAssert(document.querySelectorAll('.admin-bar-row').length===6,'Action breakdown is missing');
  const selector=document.querySelector('[aria-label="Daily chart metric"]');selector.value='cost';selector.dispatchEvent(new Event('change'));
  polishAssert(document.querySelector('.admin-chart-plot svg').getAttribute('aria-label').includes('Estimated cost'),'Cost chart did not update');
  polishAssert(document.querySelectorAll('.admin-chart-plot rect').length>0,'Seeded cost bars are missing');
  document.querySelector('.admin-user-row').click();await polishWait(()=>$('adminTitle').textContent==='User projects');
  polishAssert($('adminContent').textContent.includes('Wand selections')&&$('adminContent').textContent.includes('Mask adjustments'),'User usage summary missing');
  polishAssert(document.querySelector('.admin-chart-grid'),'Per-user graph missing');
  checks.push('Overview and per-user graphs switch metrics and expose masked edits, Harmonize, Wand, Auto Create and known cost coverage');
  document.querySelector('[data-view="users"]').click();await polishWait(()=>document.querySelector('#adminContent table'));
  const text=$('adminContent').textContent;
  polishAssert(text.includes('Auto Create')&&text.includes('estimated USD'),'Users table is missing usage/cost columns');
  if(innerWidth<600)polishAssert(document.documentElement.scrollWidth<=innerWidth+2,'Admin layout overflows on mobile');
  checks.push('User summary table includes tool counts and approximate USD; layout remains usable at this viewport');
  document.querySelector('[data-view="overview"]').click();await polishWait(()=>document.querySelector('.admin-chart-grid'));
  return {passed:checks.length,checks};
};
